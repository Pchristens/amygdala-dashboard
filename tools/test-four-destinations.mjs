import assert from 'node:assert/strict';
import fs from 'node:fs';
const html = fs.readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
const panel = fs.readFileSync(new URL('../public/panel.js', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('../public/app.js', import.meta.url), 'utf8');
const viewMap = panel.match(/VIEW_DESTINATION = Object\.freeze\(\{([^}]*)\}\)/)?.[1] || '';
const destinationMap = panel.match(/DESTINATION_VIEWS = Object\.freeze\(\{([^}]*)\}\)/)?.[1] || '';
const pairs = Object.fromEntries([...viewMap.matchAll(/(\w+): '([^']+)'/g)].map(m => [m[1], m[2]]));
const destinations = Object.fromEntries([...destinationMap.matchAll(/(\w+): \[([^\]]+)\]/g)].map(m => [m[1], [...m[2].matchAll(/'([^']+)'/g)].map(x => x[1])]));
assert.deepEqual(destinations, { activity: ['board','exhibits','tales'], people: ['residents'], work: ['workshop','orders'], lamps: ['lamps'] });
for (const views of Object.values(destinations)) for (const view of views) assert.ok(pairs[view]);
for (const dest of Object.keys(destinations)) assert.match(html, new RegExp(`data-destination="${dest}"`));
assert.equal((html.match(/class="rail-tab"/g) || []).length, 4);
assert.match(app, /function openView\(view\) \{ setDrawer\(true, view\); \}/);
assert.match(app, /VIEW_DESTINATION\[currentTab\(\)\] === b\.dataset\.destination/);
assert.match(app, /function openDestination\(dest\) \{[^\n]*lastDestinationView\[dest\][^\n]*views\[0\]/, 'a place reopens on its last-used view');
assert.match(app, /else openDestination\(b\.dataset\.destination\)/, 'the rail opens places through openDestination');
assert.match(app, /openDestination\(tabs\[index\]\.dataset\.destination\)/, 'keys 1-4 open places the same way as the rail');
assert.match(app, /drawerOpen && b\.dataset\.destination === VIEW_DESTINATION/, 'a closed drawer leaves no rail place highlighted');
assert.match(app, /if \(drawerOpen && VIEW_DESTINATION\[currentTab\(\)\] === b\.dataset\.destination\) setDrawer\(false\)/);
assert.match(app, /DESTINATION_VIEWS\[dest\]/);
assert.match(panel, /name === 'tales'.*exhibitView = 'tales'/);
assert.match(html, /<div class="scroll" id="tales" hidden><\/div>/);
const rail = html.slice(html.indexOf('<nav class="rail"'), html.indexOf('</nav>', html.indexOf('<nav class="rail"')));
assert.doesNotMatch(rail, /[✎❦☺⛩✉🕯]/u);
assert.match(app, /querySelectorAll\('\.rail-tab'\)/);
// A tab body outside the four places (a future view) still opens instead of throwing (Themis residual on 4030a04).
assert.match(fs.readFileSync(new URL('../public/panel.js', import.meta.url), 'utf8'), /const views = DESTINATION_VIEWS\[destination\] \|\| \[activeTab\]/);
