import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html = fs.readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
const panel = fs.readFileSync(new URL('../public/panel.js', import.meta.url), 'utf8');
const tabs = [...html.matchAll(/<button class="drawer-tab" role="tab"([^>]*)>/g)].map(m => m[1]);
const attr = (s, k) => (s.match(new RegExp(`(?:^|\\s)${k}="([^"]*)"`)) || [])[1];
assert.equal(tabs.length, 5);
for (const t of tabs) assert.equal(attr(t, 'tabindex'), attr(t, 'aria-selected') === 'true' ? '0' : '-1');
for (const n of ['board', 'exhibits', 'workshop', 'orders']) assert.match(html, new RegExp(`aria-labelledby="tabbtn-${n}"`));
assert.match(html, /aria-labelledby="drawer-title"/);
assert.doesNotMatch(html, /id="exhibit-tabs"|id="count-(?:board|exhibits|residents|workshop|lamps)"/);
const mk = n => ({ dataset: { tab: n }, attrs: {}, hidden: false, tabIndex: -1, setAttribute(k, v) { this.attrs[k] = v; }, focus() { ctx.focused = n; } });
const names = ['board', 'exhibits', 'tales'], els = { tabs: [...names, 'workshop', 'orders'].map(mk), bodies: ['board', 'exhibits', 'workshop', 'orders'].map(tab => ({ dataset: { tab } })) };
const switcher = { hidden: false, setAttribute(k, v) { this[k] = v; } }, title = { textContent: '' };
const talesRoot = { hidden: true };
els.exhibits = { hidden: false };
const ctx = vm.createContext({ els, activeTab: 'board', exhibitView: 'art', opts: {}, scrollBoardToBottom() {}, $: () => talesRoot, document: { querySelector: () => switcher, getElementById: () => title }, DESTINATION_VIEWS: { activity: names, people: ['residents'], work: ['workshop', 'orders'], lamps: ['lamps'] }, VIEW_DESTINATION: { board: 'activity', exhibits: 'activity', tales: 'activity', workshop: 'work', orders: 'work' }, renderTales() {} });
const a = panel.indexOf('function tabKey'), b = panel.indexOf('// ---- zone switch');
vm.runInContext(panel.slice(a, b).replace(/for \(const t of els\.tabs\) t\.addEventListener\('keydown', tabKey\);/, ''), ctx);
const key = (from, k) => { const e = { key: k, target: els.tabs[from], preventDefault() {} }; ctx.tabKey(e); };
key(0, 'ArrowRight'); assert.equal(ctx.activeTab, 'exhibits');
key(1, 'ArrowRight'); assert.equal(ctx.activeTab, 'tales'); assert.equal(els.bodies[1].hidden, false);
assert.equal(ctx.exhibitView, 'tales'); assert.equal(talesRoot.hidden, false); assert.equal(ctx.focused, 'tales');
const workTabs = els.tabs.slice(3);
vm.runInContext("selectTab('workshop')", ctx); key(3, 'ArrowRight');
assert.equal(ctx.activeTab, 'orders'); assert.equal(workTabs[0].hidden, false); assert.equal(workTabs[1].attrs['aria-selected'], 'true'); assert.equal(ctx.focused, 'orders');
console.log('ok: drawer switcher tabs and tales view');
